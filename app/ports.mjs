/**
 * 挑端口时的一个纯函数判断：这个端口，`node:test` 里的 `fetch`（undici）会不会拒绝连它。
 *
 * ---- 为什么需要这个文件（2026-10-19 定位的一条间歇红）-----------------------------
 * 症状：`node --test` 全量并发跑时偶发一两条红，单跑不复现，报
 *   `TypeError: fetch failed` + `[cause]: Error: bad port`
 * 堆栈停在 `boot()` 里的 `fetch("http://127.0.0.1:<port>/api/session")`，**不在断言上** ——
 * 所以 `tests/mutation-check.mjs` 只打印“基线 fail=1”，拿不到用例名。
 *
 * 根因：测试都用 `LINLI_PORT=0` 让系统分配端口，而 undici 会拒绝一批「浏览器视为不安全」
 * 的端口（6000、6665–6669、10080…）。Windows 的动态端口范围实测从 **1024** 起
 * （`netsh int ipv4 show dynamicport tcp` → Start Port 1024 / Number of Ports 64511），
 * 所以随机落进黑名单是真会发生的，概率小但不为零。
 *
 * 处置：不在 17 个测试文件里各写一份 fetch 重试（那是把症状按下去），
 * 而在**挑端口这一层**绕开 —— 只有 `LINLI_PORT=0`（随机端口）才重选；
 * 显式给了端口就照给的listen（生产、外壳、探针都走这条，行为一点不变）。
 *
 * 判据做成纯函数放这里，是为了能**确定性地**测那条重选分支：真机上凑一个 6000
 * 端口不可控，而这个函数的入参就是「拿到的端口」，直接喂 6000 即可。
 */

/** undici（浏览器同源）视为不安全、拒绝连接的端口。抄自 undici 的 badPorts 表。 */
export const BROWSER_BLOCKED_PORTS = new Set([
  1, 7, 9, 11, 13, 15, 17, 19, 20, 21, 22, 23, 25, 37, 42, 43, 53, 69, 77, 79, 87, 95,
  101, 102, 103, 104, 109, 110, 111, 113, 115, 117, 119, 123, 135, 137, 139, 143, 161,
  179, 389, 427, 465, 512, 513, 514, 515, 526, 530, 531, 532, 540, 548, 554, 556, 563,
  587, 601, 636, 989, 990, 993, 995, 1719, 1720, 1723, 2049, 3659, 4045, 4190, 5060,
  5061, 6000, 6566, 6665, 6666, 6667, 6668, 6669, 6679, 6697, 10080,
]);

/**
 * 这个端口能不能用。
 * @param {number} port     实际拿到的端口
 * @param {number} requested 启动时请求的端口（0 = 让系统给）
 * @returns {boolean} true = 可以用；false = 只在这种情况下要重选：请求的是随机端口、却撞进黑名单
 */
export function portAcceptable(port, requested) {
  // 显式端口一律认：用户/外壳自己指定的，哪怕它在黑名单里也不该被我们偷偷换掉
  // （换了外壳就连不上了；而且 HttpClient 不像 undici 那样禁这些端口）。
  if (requested !== 0) return true;
  return !BROWSER_BLOCKED_PORTS.has(port);
}
